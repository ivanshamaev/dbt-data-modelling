{# ============================================================================
 # Durable hash-SK гайда (план гл. 7–8, P2-11): SK = lower(md5(bk [| bk2 ...])).
 #
 # Ключ повторяется при одинаковых аргументах; разрешение идентичностей разных
 # источников и выбор версии выполняются отдельно. lower применяется К ГОТОВОМУ
 # отпечатку, а не к исходным строкам. trim/upper/типизация здесь отсутствуют.
 # concat_ws пропускает NULL; разделитель не экранируется. Для составного ключа
 # нужны непустые согласованные компоненты, не содержащие '|'. В текущем наборе
 # это идентификаторы, коды промо и даты; для произвольных строк нужно иное кодирование.
 # md5 зафиксирован ради воспроизводимости. Это не анонимизация и не доказательство
 # отсутствия коллизий; смена схемы кодирования/алгоритма требует миграции ссылок.
 #
 # Употребление: {{ hash_key('customer_id') }} или {{ hash_key(['order_id', 'cast(ts as date)']) }}
 # ========================================================================== #}
{% macro hash_key(cols) -%}
    {%- if cols is string -%}
        {%- set cols = [cols] -%}
    {%- endif -%}
    lower(md5(concat_ws('|', {{ cols | join(', ') }})))
{%- endmacro %}
