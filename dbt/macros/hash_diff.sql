{# ============================================================================
 # hash_diff — отпечаток атрибутов спутника (план гл. 9–10, P1-5).
 #
 # Зачем: без сравнения hash_diff перед вставкой спутники пухнут дублями
 # «те же выбранные атрибуты, новый timestamp». Если deleted_at включён
 # в payload, soft delete МЕНЯЕТ отпечаток, как и любое другое выбранное поле.
 #
 # NULL-политика: sentinel '~' (concat_ws молча пропускает NULL — этого
 # недостаточно для различения NULL и пустой строки, поэтому coalesce).
 # Литерал sentinel и разделитель во входных значениях могут сделать склейку
 # неоднозначной. Алгоритм и кодирование зафиксированы для текущих доменов
 # учебного источника; смена требует согласованной миграции.
 # ========================================================================== #}
{% macro hash_diff(cols) -%}
    {%- if cols is string -%}
        {%- set cols = [cols] -%}
    {%- endif -%}
    lower(md5(concat_ws('|',
    {%- for c in cols %}
    coalesce(cast({{ c }} as varchar), '~'){% if not loop.last %}, {% endif %}
    {%- endfor %}
  )))
{%- endmacro %}
