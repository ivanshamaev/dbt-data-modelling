-- L3.2 · singular-тест: суточный объём снапшотов инвентаря — в правдоподобных границах.
-- Эталон: 14 магазинов × ~2 100 SKU матрицы ≈ 29–30 тыс. строк/день (открытие магазина 16
-- и закрытие 13 в симуляции меняют объём плавно). Границы ловят потерю магазина/дня
-- или двойную заливку партиции, не шум матрицы ассортимента.
select
    _ingest_date,
    count(*) as n
from {{ ref('raw_erp__inventory') }}
group by 1
-- Нижняя граница откалибрована живым прогоном (L19): ~300 дней рампы
-- (товары launched_at распределены по истории → ранним дням мало строк).
having count(*) < 20 or count(*) > 60000
